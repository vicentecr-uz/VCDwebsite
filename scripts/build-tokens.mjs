// @ts-check
/**
 * Generates the colour-token CSS block in src/styles/global.css from
 * tokens/design-tokens.json (DTCG format). Idempotent — running it again
 * with an unchanged JSON produces no diff.
 *
 * `bun run tokens:build`
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

export const TOKENS_RELATIVE_PATH = 'tokens/design-tokens.json';
export const CSS_RELATIVE_PATH = 'src/styles/global.css';

const START_MARKER = '/* @tokens:start — GENERATED by scripts/build-tokens.mjs. Do not edit by hand; edit tokens/design-tokens.json. */';
const END_MARKER = '/* @tokens:end */';
const MARKER_RE = /\/\* @tokens:start[\s\S]*?@tokens:end \*\//;
const IMPORT_ANCHOR = '@import "tailwindcss";\n';

const isToken = (node) => (
  !!node
  && typeof node === 'object'
  && !Array.isArray(node)
  && Object.prototype.hasOwnProperty.call(node, '$value')
);

/**
 * @param {unknown} node
 * @param {string[]} pathParts
 * @param {{ path: string[], node: any }[]} out
 */
const collectTokens = (node, pathParts, out) => {
  if (isToken(node)) {
    out.push({ path: pathParts, node });
    return;
  }
  if (node && typeof node === 'object' && !Array.isArray(node)) {
    for (const key of Object.keys(node)) collectTokens(node[key], [...pathParts, key], out);
  }
};

const cssVarName = (pathParts) => `--${pathParts.join('-')}`;

/** DTCG alias `{a.b.c}` compiles to `var(--a-b-c)`; anything else passes through. */
export const compileValue = (raw) => {
  if (typeof raw === 'string') {
    const match = /^\{([^}]+)\}$/.exec(raw.trim());
    if (match) return `var(--${match[1].split('.').join('-')})`;
  }
  return raw;
};

/** Every token name defined in the JSON, across all three tiers. */
export function collectAllTokenNames(json) {
  const tokens = [];
  collectTokens(json, [], tokens);
  return new Set(tokens.map(({ path: p }) => cssVarName(p)));
}

function buildDeclarations(json) {
  const tokens = [];
  collectTokens(json, [], tokens);

  const refDecls = [];
  const sysLightDecls = [];
  const sysDarkDecls = [];
  const compDecls = [];

  for (const { path: p, node } of tokens) {
    const name = cssVarName(p);
    const tier = p[0];
    if (tier === 'ref') {
      refDecls.push(`  ${name}: ${compileValue(node.$value)};`);
    } else if (tier === 'sys') {
      const modes = node.$extensions && node.$extensions.modes;
      const light = compileValue(modes ? modes.light : node.$value);
      const dark = compileValue(modes ? modes.dark : node.$value);
      sysLightDecls.push(`  ${name}: ${light};`);
      sysDarkDecls.push(`  ${name}: ${dark};`);
    } else if (tier === 'comp') {
      compDecls.push(`  ${name}: ${compileValue(node.$value)};`);
    }
  }

  return { refDecls, sysLightDecls, sysDarkDecls, compDecls };
}

/** Pure: DTCG JSON in, generated CSS block (with markers) out. */
export function generateTokenBlock(json) {
  const { refDecls, sysLightDecls, sysDarkDecls, compDecls } = buildDeclarations(json);

  const rootBlock = [
    ':root {',
    ...refDecls,
    ...sysLightDecls,
    ...compDecls,
    '}',
  ].join('\n');

  const darkMediaBlock = [
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    ...sysDarkDecls.map((line) => `  ${line}`),
    '  }',
    '}',
  ].join('\n');

  const darkAttrBlock = [
    ':root[data-theme="dark"] {',
    ...sysDarkDecls,
    '}',
  ].join('\n');

  return [START_MARKER, rootBlock, '', darkMediaBlock, '', darkAttrBlock, END_MARKER].join('\n');
}

/**
 * Splice the generated block into existing CSS source (replacing a prior
 * generated block if markers are present, else inserting after the Tailwind
 * import). Pure — returns the next source and whether it differs.
 * @returns {{ next: string, changed: boolean }}
 */
export function applyTokenBlock(cssSource, generatedBlock) {
  if (MARKER_RE.test(cssSource)) {
    const next = cssSource.replace(MARKER_RE, generatedBlock);
    return { next, changed: next !== cssSource };
  }
  if (!cssSource.includes(IMPORT_ANCHOR)) {
    throw new Error(`Could not find ${JSON.stringify(IMPORT_ANCHOR.trim())} in ${CSS_RELATIVE_PATH}`);
  }
  const next = cssSource.replace(IMPORT_ANCHOR, `${IMPORT_ANCHOR}\n${generatedBlock}\n`);
  return { next, changed: next !== cssSource };
}

function main() {
  const root = process.cwd();
  const tokensPath = path.join(root, TOKENS_RELATIVE_PATH);
  const cssPath = path.join(root, CSS_RELATIVE_PATH);

  const json = JSON.parse(readFileSync(tokensPath, 'utf8'));
  const block = generateTokenBlock(json);
  const source = readFileSync(cssPath, 'utf8');
  const { next, changed } = applyTokenBlock(source, block);

  if (changed) {
    writeFileSync(cssPath, next);
    console.log(`tokens: wrote ${CSS_RELATIVE_PATH}`);
  } else {
    console.log(`tokens: ${CSS_RELATIVE_PATH} already up to date`);
  }
}

if (import.meta.main) main();
